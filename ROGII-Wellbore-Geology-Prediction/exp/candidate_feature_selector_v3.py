"""Test-available whole-well candidate selector with conservative safety gates.

This is deliberately separate from candidate_path_ranker_v2.py.  It adds
candidate-relative evidence already generated by the inference pipeline and
evaluates only out-of-fold well predictions.
"""
from pathlib import Path
import json
import os
import sys

import joblib
import numpy as np
import pandas as pd
from lightgbm import LGBMRegressor
from sklearn.model_selection import GroupKFold

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "exp/results/candidate_feature_selector_v3"
OUT.mkdir(parents=True, exist_ok=True)
sys.path.insert(0, str(ROOT / "exp"))
from candidate_path_ranker_v2 import make_candidates, rmse  # noqa: E402


def _corr(a, b):
    a, b = np.asarray(a), np.asarray(b)
    ok = np.isfinite(a) & np.isfinite(b)
    if ok.sum() < 5 or np.std(a[ok]) < 1e-7 or np.std(b[ok]) < 1e-7:
        return 0.0
    return float(np.corrcoef(a[ok], b[ok])[0, 1])


def _gap(a, b):
    z = np.asarray(a) - np.asarray(b)
    return float(np.sqrt(np.nanmean(z * z)))


def features(g, pred, candidates, cid):
    x = g.d_md.to_numpy(float)
    gr = g.gr.to_numpy(float)
    dz = g.d_z.to_numpy(float)
    grad = np.gradient(pred)
    curv = np.gradient(grad)
    stack = np.stack(list(candidates.values()))
    center = np.median(stack, axis=0)
    dispersion = np.std(stack, axis=0)
    f = {
        "n": len(g), "xspan": np.ptp(x), "zspan": np.ptp(dz),
        "frac_end": float(g.frac.max()), "gr_std": np.std(gr),
        "gr_rough": np.std(np.gradient(gr)),
        "pred_mean": np.mean(pred), "pred_std": np.std(pred),
        "pred_span": np.ptp(pred), "pred_end": pred[-1],
        "pred_slope": np.polyfit(x, pred, 1)[0] if np.ptp(x) > 1 else 0.,
        "rough1": np.sqrt(np.mean(grad ** 2)),
        "rough2": np.sqrt(np.mean(curv ** 2)),
        "rough2_p90": np.quantile(np.abs(curv), .9),
        "center_gap": _gap(pred, center),
        "disp_mean": np.mean(dispersion),
        "disp_p90": np.quantile(dispersion, .9),
        "corr_gr": _corr(pred, gr), "corr_dz": _corr(pred, dz),
        "pfx_gr_rmse": float(g.pfx_gr_rmse.mean()),
        "ncc8_score_mean": float(g.ncc8_s.mean()),
        "ncc15_score_mean": float(g.ncc15_s.mean()),
        "ncc25_score_mean": float(g.ncc25_s.mean()),
        "ncc_score_sharpness": float(
            np.mean(np.maximum.reduce([g.ncc8_s, g.ncc15_s, g.ncc25_s]) -
                    np.minimum.reduce([g.ncc8_s, g.ncc15_s, g.ncc25_s]))),
        "sp_std": float(g.sp_std.mean()), "sp_dmin": float(g.sp_dmin.mean()),
    }
    # Candidate-to-signal trajectory agreement. These columns are all produced
    # at inference and do not use hidden TVT.
    trajectory_cols = [
        "pf_d", "pf3_d", "beam_d", "ncc8_d", "ncc15_d", "ncc25_d",
        "sp_mean_d",
    ] + [c for c in g.columns if c.startswith("tda") or c.startswith("tdpf")]
    for col in trajectory_cols:
        q = g[col].to_numpy(float)
        f[f"gap_{col}"] = _gap(pred, q)
        f[f"corr_{col}"] = _corr(pred, q)
        # Residual smoothness distinguishes a datum mismatch from a shape miss.
        f[f"resstd_{col}"] = float(np.nanstd(pred - q))
    # Relative distance to every candidate is useful because good choices occur
    # in stable clusters, while isolated alternatives are risky.
    for other, q in candidates.items():
        f[f"cgap_{other}"] = _gap(pred, q)
    f.update({f"is_{k}": float(cid == k) for k in candidates})
    return f


def pooled(truths, paths, selection):
    y, p = [], []
    for w, choice in selection.items():
        y.append(truths[w])
        if isinstance(choice, str):
            p.append(paths[w][choice])
        else:
            ids, weights = choice
            p.append(sum(a * paths[w][c] for c, a in zip(ids, weights)))
    return rmse(np.concatenate(y), np.concatenate(p))


def worst_decile(truths, paths, selection, base):
    rows = []
    for w in selection:
        y = truths[w]
        c = selection[w]
        p = paths[w][c] if isinstance(c, str) else sum(
            a * paths[w][z] for z, a in zip(*c))
        rows.append((w, rmse(y, p), rmse(y, paths[w][base])))
    q = pd.DataFrame(rows, columns=["well", "new", "base"]).sort_values(
        "base", ascending=False).head(max(1, int(np.ceil(.1 * len(rows)))))
    return {"new": float(np.sqrt(np.mean(q.new ** 2))),
            "base": float(np.sqrt(np.mean(q.base ** 2)))}


def main(limit=180, folds=5):
    d = pd.read_pickle(ROOT / "r_v4b/train_feats.pkl")
    pack = joblib.load(ROOT / "r_v4b/stack_v4_oofs.joblib")
    oo = pack["oofs"]
    rng = np.random.RandomState(20260730)
    wells = sorted(d.well.unique())
    if limit:
        wells = sorted(rng.choice(wells, min(limit, len(wells)),
                                  replace=False).tolist())
        d = d[d.well.isin(wells)]
    rows, truths, paths = [], {}, {}
    for w, g in d.groupby("well", sort=True):
        cands = make_candidates(g, oo)
        truths[w] = g.target.to_numpy(float)
        paths[w] = cands
        for cid, pred in cands.items():
            z = features(g, pred, cands, cid)
            z.update(well=w, candidate=cid,
                     mse=float(np.mean((truths[w] - pred) ** 2)))
            rows.append(z)
    tab = pd.DataFrame(rows)
    base = "weighted"
    base_mse = tab[tab.candidate.eq(base)].set_index("well").mse
    tab["regret"] = tab.mse - tab.well.map(base_mse)
    cols = [c for c in tab if c not in
            ("well", "candidate", "mse", "regret")]
    X = tab[cols].replace([np.inf, -np.inf], np.nan).fillna(0)
    pred = np.zeros(len(tab))
    gkf = GroupKFold(folds)
    for fold, (tr, va) in enumerate(gkf.split(X, groups=tab.well)):
        model = LGBMRegressor(
            n_estimators=700, learning_rate=.02, num_leaves=12,
            max_depth=5, min_child_samples=35, reg_alpha=2, reg_lambda=15,
            colsample_bytree=.7, verbosity=-1, random_state=900 + fold,
            n_jobs=max(1, os.cpu_count() // 2))
        model.fit(X.iloc[tr], tab.regret.iloc[tr])
        pred[va] = model.predict(X.iloc[va])
    tab["score"] = pred
    baseline = {w: base for w in truths}
    oracle = {w: q.loc[q.mse.idxmin(), "candidate"]
              for w, q in tab.groupby("well")}
    raw = {w: q.loc[q.score.idxmin(), "candidate"]
           for w, q in tab.groupby("well")}
    out = {
        "wells": len(truths), "rows": int(sum(map(len, truths.values()))),
        "baseline": pooled(truths, paths, baseline),
        "raw": pooled(truths, paths, raw),
        "oracle": pooled(truths, paths, oracle),
    }
    # A switch is permitted only when the predicted advantage over weighted is
    # substantial. This directly controls selector tail risk.
    gates = {}
    for threshold in (0, 1, 2, 4, 6, 9, 12, 16):
        sel = {}
        switches = 0
        for w, q in tab.groupby("well"):
            qb = float(q.loc[q.candidate.eq(base), "score"].iloc[0])
            best = q.loc[q.score.idxmin()]
            if best.candidate != base and qb - best.score >= threshold:
                sel[w] = best.candidate
                switches += 1
            else:
                sel[w] = base
        gates[str(threshold)] = {
            "rmse": pooled(truths, paths, sel), "switches": switches,
            "worst_decile": worst_decile(truths, paths, sel, base)}
    out["gates"] = gates
    print(json.dumps(out, indent=2))
    (OUT / ("pilot_summary.json" if limit else "summary.json")).write_text(
        json.dumps(out, indent=2))
    tab[["well", "candidate", "mse", "regret", "score"]].to_csv(
        OUT / ("pilot_scores.csv" if limit else "scores.csv"), index=False)


if __name__ == "__main__":
    main(int(sys.argv[1]) if len(sys.argv) > 1 else 180)
